//! lacks shows in English, or in the core's Italian where the core has the word. The core's own words (a level's name, a
//! schedule's name, what a drawing prints) are in `language.rs` and are not repeated here.

/// An element category's name in Italian, of one (`Muro`) or of several (`Muri`); none for a category this table does not
/// know, which then shows as the window's own English.
pub(super) fn category(category: &str, several: bool) -> Option<&'static str> {
    let (one, many) = match category {
        "wall" => ("Muro", "Muri"),
        "door" => ("Porta", "Porte"),
        "window" => ("Finestra", "Finestre"),
        "floor" => ("Pavimento", "Pavimenti"),
        "room" => ("Locale", "Locali"),
        "level" => ("Livello", "Livelli"),
        "grid" => ("Griglia", "Griglie"),
        "dimension" => ("Quota", "Quote"),
        "tag" => ("Etichetta", "Etichette"),
        "section" => ("Sezione", "Sezioni"),
        "elevation" => ("Prospetto", "Prospetti"),
        "sheet" => ("Tavola", "Tavole"),
        "viewport" => ("Vista su tavola", "Viste su tavola"),
        "column" => ("Pilastro", "Pilastri"),
        "component" => ("Componente", "Componenti"),
        "stair" => ("Scala", "Scale"),
        "roof" => ("Tetto", "Tetti"),
        "ceiling" => ("Controsoffitto", "Controsoffitti"),
        "mass" => ("Massa", "Masse"),
        "massfloor" => ("Piano di massa", "Piani di massa"),
        "ramp" => ("Rampa", "Rampe"),
        "railing" => ("Ringhiera", "Ringhiere"),
        "beam" => ("Trave", "Travi"),
        "structuralcolumn" => ("Pilastro strutturale", "Pilastri strutturali"),
        "footing" => ("Plinto", "Plinti"),
        "pipe" => ("Tubazione", "Tubazioni"),
        "conduit" => ("Tubo protettivo", "Tubi protettivi"),
        "cabletray" => ("Passerella portacavi", "Passerelle portacavi"),
        "wire" => ("Filo", "Fili"),
        "cable" => ("Cavo", "Cavi"),
        "downconductor" => ("Calata", "Calate"),
        "groundconductor" => ("Conduttore di terra", "Conduttori di terra"),
        "text" => ("Nota di testo", "Note di testo"),
        "spot" => ("Quota altimetrica", "Quote altimetriche"),
        "schedule" => ("Abaco", "Abachi"),
        "view3d" => ("Vista 3D", "Viste 3D"),
        "link" => ("Modello collegato", "Modelli collegati"),
        _ => return None,
    };
    Some(if several { many } else { one })
}

